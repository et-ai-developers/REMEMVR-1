"""
Plotting script for RQ 6.2.5 - Calibration Age Effects

GENERATED BY: Claude Code
DATE: 2025-12-11
PURPOSE: Create publication-ready age tertile calibration trajectory plot

DATA SOURCE:
- data/step04_age_tertile_trajectories.csv (pre-aggregated means by age tertile and test)

PLOTS GENERATED:
1. age_tertile_calibration_trajectories.png - Calibration trajectories for Young/Middle/Older age tertiles
"""

import sys
from pathlib import Path

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd
import matplotlib.pyplot as plt
from tools.plotting import set_plot_style_defaults

# =============================================================================
# SETUP
# =============================================================================

# Get absolute path to RQ root (plots.py is in results/ch6/6.2.5/plots/)
RQ_ROOT = Path(__file__).resolve().parent.parent

# Apply consistent plotting theme from config/plotting.yaml
set_plot_style_defaults()

print("Starting plotting for RQ 6.2.5 (Calibration Age Effects)...")
print(f"RQ root: {RQ_ROOT}")

# =============================================================================
# PLOT: AGE TERTILE CALIBRATION TRAJECTORIES
# =============================================================================

print("\nGenerating Age Tertile Calibration Trajectories Plot...")

# Load pre-aggregated plot source data
df_tertile = pd.read_csv(RQ_ROOT / "data" / "step04_age_tertile_trajectories.csv")
print(f"  Loaded {len(df_tertile)} rows from step04_age_tertile_trajectories.csv")
print(f"  Columns: {list(df_tertile.columns)}")
print(f"  Age tertiles: {sorted(df_tertile['age_tertile'].unique())}")
print(f"  Test sessions: {sorted(df_tertile['test'].unique())}")

# Define test session order and numeric mapping for x-axis
test_order = ['T1', 'T2', 'T3', 'T4']
test_numeric = {'T1': 1, 'T2': 2, 'T3': 3, 'T4': 4}

# Define age tertile colors (distinct palette)
tertile_colors = {
    'Young': '#3498DB',    # Blue (younger)
    'Middle': '#95A5A6',   # Gray (middle)
    'Older': '#E74C3C'     # Red (older)
}

# Define age tertile order
tertile_order = ['Young', 'Middle', 'Older']

# Create figure
fig, ax = plt.subplots(figsize=(10, 6))

# Plot each age tertile
for tertile in tertile_order:
    df_tert = df_tertile[df_tertile['age_tertile'] == tertile].copy()

    # Sort by test session
    df_tert['test_num'] = df_tert['test'].map(test_numeric)
    df_tert = df_tert.sort_values('test_num')

    # Extract data
    x = df_tert['test_num'].values
    y = df_tert['mean_calibration'].values
    yerr_lower = df_tert['mean_calibration'].values - df_tert['CI_lower'].values
    yerr_upper = df_tert['CI_upper'].values - df_tert['mean_calibration'].values
    n_participants = df_tert['N'].values[0]  # Sample size (same for all tests in tertile)

    # Get color
    color = tertile_colors.get(tertile, '#95A5A6')

    # Plot line with markers
    label = f'{tertile} (n={n_participants})'
    ax.plot(x, y, 'o-', label=label, color=color, linewidth=2.5, markersize=8, alpha=0.9)

    # Add error bars (95% CI)
    ax.errorbar(x, y, yerr=[yerr_lower, yerr_upper],
                fmt='none', color=color, capsize=5, capthick=2, alpha=0.7)

# Add horizontal line at calibration=0 (perfect calibration)
ax.axhline(y=0, color='black', linestyle='--', linewidth=1.5, alpha=0.5)
ax.text(4.2, 0.05, 'Perfect\nCalibration', fontsize=9, alpha=0.7, ha='left', va='bottom')

# Add interpretation regions
ax.fill_between([0.5, 4.5], 0, 3, alpha=0.03, color='red')  # Overconfident region
ax.fill_between([0.5, 4.5], -3, 0, alpha=0.03, color='blue')  # Underconfident region
ax.text(0.6, 1.5, 'OVERCONFIDENT', fontsize=9, alpha=0.4, rotation=90, va='center')
ax.text(0.6, -1.5, 'UNDERCONFIDENT', fontsize=9, alpha=0.4, rotation=90, va='center')

# Formatting
ax.set_xlabel('Test Session', fontweight='bold', fontsize=12)
ax.set_ylabel('Mean Calibration\n(Confidence \u2212 Accuracy)', fontweight='bold', fontsize=12)
ax.set_title('RQ 6.2.5: Calibration Trajectories by Age Tertile', fontweight='bold', pad=15, fontsize=14)
ax.set_xticks([1, 2, 3, 4])
ax.set_xticklabels(['T1\n(Encoding)', 'T2\n(~24h)', 'T3\n(~72h)', 'T4\n(~144h)'])
ax.set_xlim(0.5, 4.5)
ax.legend(title='Age Tertile', loc='upper right', framealpha=0.95)
ax.grid(True, alpha=0.3)

plt.tight_layout()

# Save plot
output_path = RQ_ROOT / "plots" / "age_tertile_calibration_trajectories.png"
fig.savefig(output_path, dpi=300, bbox_inches='tight')
print(f"  -> Saved: {output_path}")
plt.close()

# =============================================================================
# SUMMARY
# =============================================================================

print("\n" + "="*70)
print("PLOTTING COMPLETE")
print("="*70)
print(f"Total plots generated: 1")
print(f"  - plots/age_tertile_calibration_trajectories.png")
print("\nPlot shows calibration trajectories across 4 test sessions (T1-T4)")
print("for Young/Middle/Older age tertiles with 95% CI error bars.")
print("\nKey finding: NULL Age x Time interaction (p=0.735)")
print("Age-invariant calibration decline paralleling Ch5 accuracy findings.")
print("="*70)
