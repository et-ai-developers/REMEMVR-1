#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Plotting script for RQ 6.1.1 - Functional Form Comparison for Confidence Decline

GENERATED BY: rq_plots agent (v4.0.0) - MODIFIED FOR DIRECT DATA LOADING
DATE: 2025-12-11
PURPOSE: Create publication-ready plots from analysis outputs

NOTE: This RQ did not pre-generate plot source CSVs (Option B not followed).
      Plots generated directly from step04_lmm_input.csv and step06_aic_comparison.csv.

PLOTS GENERATED:
1. confidence_trajectory_theta.png - Theta-scale confidence trajectory over time (TSVR_hours)
2. confidence_trajectory_probability.png - Probability-scale confidence trajectory (Decision D069 dual-scale)
3. model_comparison.png - Bar chart of top 10 models by Akaike weight
"""

from pathlib import Path
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import sys

# Add project root to path for tools import
# Path: plots.py -> plots/ -> 6.1.1/ -> ch6/ -> results/ -> REMEMVR/
project_root = Path(__file__).parent.parent.parent.parent.parent
sys.path.insert(0, str(project_root))

from tools.plotting import (
    set_plot_style_defaults,
    plot_trajectory,
    plot_trajectory_probability,
    plot_comparison_bars
)

# =============================================================================
# SETUP
# =============================================================================

# Get absolute path to RQ root (plots.py is in results/ch6/6.1.1/plots/)
RQ_ROOT = Path(__file__).parent.parent

# Apply consistent plotting theme from config/plotting.yaml
set_plot_style_defaults()

print("=" * 70)
print("PLOTTING FOR RQ 6.1.1: Functional Form Comparison (Confidence)")
print("=" * 70)
print(f"RQ root: {RQ_ROOT}")
print()

# =============================================================================
# LOAD DATA
# =============================================================================

print("Loading analysis data...")

# Load LMM input data (theta scores with time variables)
df_lmm = pd.read_csv(RQ_ROOT / "data" / "step04_lmm_input.csv")
print(f"  Loaded {len(df_lmm)} rows from step04_lmm_input.csv")
print(f"  Columns: {list(df_lmm.columns)}")
print(f"  Theta range: [{df_lmm['theta_All'].min():.2f}, {df_lmm['theta_All'].max():.2f}]")
print(f"  Time range (TSVR_hours): [{df_lmm['TSVR_hours'].min():.1f}, {df_lmm['TSVR_hours'].max():.1f}]")
print()

# Load model comparison data
df_models = pd.read_csv(RQ_ROOT / "data" / "step06_aic_comparison.csv")
print(f"  Loaded {len(df_models)} models from step06_aic_comparison.csv")
print(f"  Best model: {df_models[df_models['is_best']]['model_name'].values[0]} (weight={df_models[df_models['is_best']]['akaike_weight'].values[0]:.1%})")
print()

# =============================================================================
# PLOT 1: TRAJECTORY (THETA-SCALE)
# =============================================================================

print("Generating Plot 1: Theta-scale confidence trajectory...")

# Calculate observed statistics (mean +/- SEM per time point)
observed_stats = df_lmm.groupby('TSVR_hours').agg(
    theta_mean=('theta_All', 'mean'),
    theta_sem=('theta_All', lambda x: x.std() / np.sqrt(len(x))),
    n=('theta_All', 'count')
).reset_index()

print(f"  Aggregated {len(observed_stats)} time points")

# For fitted curve, we'll use the observed means (since we don't have LMM predictions pre-computed)
# This is a simplified trajectory plot showing observed data with error bars
time_points = observed_stats['TSVR_hours'].values
theta_means = observed_stats['theta_mean'].values

# Create simple trajectory plot
fig_theta, ax_theta = plt.subplots(figsize=(10, 6))

# Plot observed data with error bars
ax_theta.errorbar(
    observed_stats['TSVR_hours'],
    observed_stats['theta_mean'],
    yerr=observed_stats['theta_sem'],
    fmt='o-',
    color='#2C3E50',
    markersize=8,
    capsize=5,
    capthick=2,
    linewidth=2.5,
    label='Observed Confidence (Mean +/- SEM)',
    alpha=0.9
)

# Formatting
ax_theta.set_xlabel('Hours Since VR Encoding (TSVR)', fontweight='bold')
ax_theta.set_ylabel('Confidence Ability (Theta)', fontweight='bold')
ax_theta.set_title('RQ 6.1.1: Confidence Trajectory - Theta Scale', fontweight='bold', pad=15)
ax_theta.legend(loc='upper right', framealpha=0.95)
ax_theta.grid(True, alpha=0.3)
ax_theta.axhline(y=0, color='gray', linestyle='--', linewidth=1, alpha=0.5)

plt.tight_layout()

# Save
output_path_theta = RQ_ROOT / "plots" / "confidence_trajectory_theta.png"
fig_theta.savefig(output_path_theta, dpi=300, bbox_inches='tight')
print(f"  Saved: {output_path_theta.name}")
print()

# =============================================================================
# PLOT 2: TRAJECTORY (PROBABILITY-SCALE) - Decision D069
# =============================================================================

print("Generating Plot 2: Probability-scale confidence trajectory (Decision D069)...")

# Load item parameters to get mean discrimination
item_params_path = RQ_ROOT / "data" / "step03_item_parameters.csv"

if item_params_path.exists():
    # Use plot_trajectory_probability function
    # First, need to prepare data in expected format (wide format with theta columns)

    # Pivot to wide format for plot_trajectory_probability
    df_wide = df_lmm.pivot(index='UID', columns='test', values='theta_All').reset_index()

    # Rename columns to match expected format
    df_wide.columns = ['UID', 'theta_T1', 'theta_T2', 'theta_T3', 'theta_T4']

    # Add TSVR mapping for each test
    tsvr_mapping = df_lmm.groupby('test')['TSVR_hours'].first().to_dict()

    # Create long format with theta and TSVR
    df_for_prob = df_lmm[['UID', 'test', 'theta_All', 'TSVR_hours']].copy()
    df_for_prob = df_for_prob.rename(columns={'theta_All': 'All_Theta', 'TSVR_hours': 'test_time'})

    # Use plot_trajectory_probability
    fig_prob, ax_prob, df_prob_transformed = plot_trajectory_probability(
        df_thetas=df_for_prob,
        item_parameters_path=item_params_path,
        time_var='test_time',
        factors=['All'],
        title='RQ 6.1.1: Confidence Trajectory - Probability Scale',
        figsize=(10, 6),
        output_path=RQ_ROOT / "plots" / "confidence_trajectory_probability.png",
        show_errorbar=True
    )

    print(f"  Saved: confidence_trajectory_probability.png")
else:
    print(f"  WARNING: Item parameters file not found - skipping probability plot")
    print(f"    Expected: {item_params_path}")

print()

# =============================================================================
# PLOT 3: MODEL COMPARISON (TOP 10 MODELS)
# =============================================================================

print("Generating Plot 3: Model comparison (Top 10 by Akaike weight)...")

# Select top 10 models by Akaike weight
df_top10 = df_models.nlargest(10, 'akaike_weight').copy()

# Create bar plot
fig_comp, ax_comp = plt.subplots(figsize=(12, 6))

# Create colors: best model in red, others in blue
colors = ['#E74C3C' if is_best else '#3498DB' for is_best in df_top10['is_best']]

# Plot bars
bars = ax_comp.barh(
    range(len(df_top10)),
    df_top10['akaike_weight'],
    color=colors,
    alpha=0.8,
    edgecolor='black',
    linewidth=0.5
)

# Add percentage labels
for i, (weight, model_name) in enumerate(zip(df_top10['akaike_weight'], df_top10['model_name'])):
    ax_comp.text(
        weight + 0.01,
        i,
        f'{weight:.1%}',
        va='center',
        fontsize=9,
        fontweight='bold'
    )

# Formatting
ax_comp.set_yticks(range(len(df_top10)))
ax_comp.set_yticklabels(df_top10['model_name'], fontsize=10)
ax_comp.set_xlabel('Akaike Weight (Model Probability)', fontweight='bold')
ax_comp.set_title('RQ 6.1.1: Top 10 Models by Akaike Weight', fontweight='bold', pad=15)
ax_comp.set_xlim(0, df_top10['akaike_weight'].max() * 1.15)
ax_comp.grid(True, alpha=0.3, axis='x')

# Add legend
from matplotlib.patches import Patch
legend_elements = [
    Patch(facecolor='#E74C3C', edgecolor='black', label='Best Model'),
    Patch(facecolor='#3498DB', edgecolor='black', label='Other Models')
]
ax_comp.legend(handles=legend_elements, loc='lower right', framealpha=0.95)

# Invert y-axis so best model is at top
ax_comp.invert_yaxis()

plt.tight_layout()

# Save
output_path_comp = RQ_ROOT / "plots" / "model_comparison.png"
fig_comp.savefig(output_path_comp, dpi=300, bbox_inches='tight')
print(f"  Saved: {output_path_comp.name}")
print()

# =============================================================================
# SUMMARY
# =============================================================================

print("=" * 70)
print("PLOTTING COMPLETE")
print("=" * 70)
print(f"Total plots generated: 3")
print(f"  - confidence_trajectory_theta.png (theta-scale)")
print(f"  - confidence_trajectory_probability.png (probability-scale, D069)")
print(f"  - model_comparison.png (top 10 models)")
print()
print(f"Best model: {df_models[df_models['is_best']]['model_name'].values[0]}")
print(f"Akaike weight: {df_models[df_models['is_best']]['akaike_weight'].values[0]:.1%}")
print()
print("All plots saved with 300 DPI publication quality.")
print("=" * 70)
