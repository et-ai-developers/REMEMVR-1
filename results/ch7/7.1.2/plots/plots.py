from pathlib import Path
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from tools.plotting import (
    set_plot_style_defaults,
    plot_comparison_bars
)

# =============================================================================
# SETUP
# =============================================================================

# Get absolute path to RQ root (plots.py is in results/ch7/7.1.2/plots/)
RQ_ROOT = Path(__file__).parent.parent

# Apply consistent plotting theme from config/plotting.yaml
set_plot_style_defaults()

print("Starting plotting for RQ 7.1.2...")
print(f"RQ root: {RQ_ROOT}")

# =============================================================================
# PLOT 1: INTERCEPT VS SLOPE R-SQUARED COMPARISON
# =============================================================================

print("\nGenerating Plot 1: Intercept vs Slope R-squared comparison...")

# Load plot source CSV (created by analysis pipeline)
df_comparison = pd.read_csv(RQ_ROOT / "plots" / "intercept_vs_slope_comparison_data.csv")
print(f"  Loaded {len(df_comparison)} rows from intercept_vs_slope_comparison_data.csv")
print(f"  Columns: {list(df_comparison.columns)}")

# Generate comparison bar plot
fig_comp, ax_comp = plot_comparison_bars(
    df=df_comparison,
    x_col='model',
    y_col='r_squared',
    ci_lower_col='r_squared_ci_lower',
    ci_upper_col='r_squared_ci_upper',
    xlabel='Model Type',
    ylabel='R-squared',
    title='RQ 7.1.2: Cognitive Tests Predict Intercept > Slope',
    colors={'intercept': '#E74C3C', 'slope': '#3498DB'},
    figsize=(8, 6),
    output_path=RQ_ROOT / "plots" / "intercept_vs_slope_comparison.png"
)

print(f"  ✓ Saved: plots/intercept_vs_slope_comparison.png")

# =============================================================================
# PLOT 2: REGRESSION DIAGNOSTICS SUMMARY
# =============================================================================

print("\nGenerating Plot 2: Regression diagnostics summary...")

# Load plot source CSV
df_diagnostics = pd.read_csv(RQ_ROOT / "plots" / "regression_diagnostics_data.csv")
print(f"  Loaded {len(df_diagnostics)} rows from regression_diagnostics_data.csv")

# Create diagnostic test summary visualization
# Group by model and test type to show pass/fail rates
models = df_diagnostics['model'].unique()
test_types = df_diagnostics['test_type'].unique()

# Create summary data for plotting
test_summary = []
for model in models:
    for test_type in test_types:
        test_data = df_diagnostics[
            (df_diagnostics['model'] == model) & 
            (df_diagnostics['test_type'] == test_type)
        ]
        if len(test_data) > 0:
            pass_rate = test_data['assumption_met'].mean()
            test_summary.append({
                'model': model,
                'test_type': test_type,
                'pass_rate': pass_rate
            })

df_test_summary = pd.DataFrame(test_summary)

# Create diagnostic summary bar plot
if len(df_test_summary) > 0:
    fig_diag, ax_diag = plot_comparison_bars(
        df=df_test_summary,
        x_col='test_type',
        y_col='pass_rate',
        group_col='model',
        xlabel='Diagnostic Test Type',
        ylabel='Test Pass Rate (0=Fail, 1=Pass)',
        title='RQ 7.1.2: Regression Diagnostic Test Results',
        colors={'intercept': '#E74C3C', 'slope': '#3498DB'},
        figsize=(12, 6),
        output_path=RQ_ROOT / "plots" / "regression_diagnostics.png"
    )
    print(f"  ✓ Saved: plots/regression_diagnostics.png")
else:
    print("  Warning: No diagnostic test summary could be created from available data")

# =============================================================================
# SUMMARY
# =============================================================================

print("\n" + "="*70)
print("PLOTTING COMPLETE")
print("="*70)
print(f"Total plots generated: 2")
print(f"  - plots/intercept_vs_slope_comparison.png")
print(f"  - plots/regression_diagnostics.png")
print("\nAll plots saved with 300 DPI publication quality.")
print("="*70)