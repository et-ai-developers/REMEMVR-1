from pathlib import Path
import pandas as pd
import numpy as np
from tools.plotting import (
    set_plot_style_defaults,
    plot_diagnostics,
    plot_comparison_bars
)

# =============================================================================
# SETUP
# =============================================================================

# Get absolute path to RQ root (plots.py is in results/ch7/7.5.1/plots/)
RQ_ROOT = Path(__file__).parent.parent

# Apply consistent plotting theme from config/plotting.yaml
set_plot_style_defaults()

print("Starting plotting for RQ 7.5.1...")
print(f"RQ root: {RQ_ROOT}")

# =============================================================================
# PLOT 1: REGRESSION DIAGNOSTICS (2x2 GRID)
# =============================================================================

print("\nGenerating Plot 1: Regression diagnostics...")

# Load regression residuals data (created by analysis pipeline)
df_residuals = pd.read_csv(RQ_ROOT / "data" / "step05_residuals_data.csv")
print(f"  Loaded {len(df_residuals)} observations from step05_residuals_data.csv")
print(f"  Columns: {list(df_residuals.columns)}")

# Generate 2x2 diagnostic plots
fig_diag, axes_diag = plot_diagnostics(
    df=df_residuals,
    fitted_col='fitted',
    residuals_col='residual',
    group_col=None,  # No grouping for regression diagnostics
    figsize=(12, 10),
    output_path=RQ_ROOT / "plots" / "diagnostic_plots.png"
)

print(f"  ✓ Saved: plots/diagnostic_plots.png")

# =============================================================================
# PLOT 2: EFFECT SIZES COMPARISON
# =============================================================================

print("\nGenerating Plot 2: Effect sizes comparison...")

# Load effect sizes data
df_effect_sizes = pd.read_csv(RQ_ROOT / "data" / "step06_effect_sizes.csv")
print(f"  Loaded {len(df_effect_sizes)} effect size measures from step06_effect_sizes.csv")

# Generate effect sizes bar plot
fig_effects, ax_effects = plot_comparison_bars(
    df=df_effect_sizes,
    x_col='measure',
    y_col='value',
    group_col=None,
    ci_lower_col='ci_lower',
    ci_upper_col='ci_upper',
    annotation_col='interpretation',
    xlabel='Effect Size Measure',
    ylabel='Value',
    title='RQ 7.5.1: Effect Sizes for Self-Report Predictors',
    figsize=(10, 6),
    output_path=RQ_ROOT / "plots" / "effect_sizes.png"
)

print(f"  ✓ Saved: plots/effect_sizes.png")

# =============================================================================
# PLOT 3: PREDICTOR IMPORTANCE RANKING
# =============================================================================

print("\nGenerating Plot 3: Predictor importance ranking...")

# Load predictor importance data
df_importance = pd.read_csv(RQ_ROOT / "data" / "step06_relative_importance.csv")
print(f"  Loaded {len(df_importance)} predictors from step06_relative_importance.csv")

# Clean predictor names for display
df_importance['predictor_clean'] = df_importance['predictor'].str.replace('_z', '').str.replace('_', ' ').str.title()

# Sort by rank for proper display order
df_importance = df_importance.sort_values('rank')

# Generate predictor importance bar plot
fig_importance, ax_importance = plot_comparison_bars(
    df=df_importance,
    x_col='predictor_clean',
    y_col='sr2',
    group_col=None,
    annotation_col='percent_of_r2',  # Will show percentage labels
    xlabel='Predictor',
    ylabel='Semi-partial r² (Unique Variance)',
    title='RQ 7.5.1: Predictor Relative Importance',
    figsize=(10, 6),
    output_path=RQ_ROOT / "plots" / "predictor_importance.png"
)

print(f"  ✓ Saved: plots/predictor_importance.png")

# =============================================================================
# PLOT 4: CROSS-VALIDATION PERFORMANCE
# =============================================================================

print("\nGenerating Plot 4: Cross-validation performance...")

# Load cross-validation results
df_cv = pd.read_csv(RQ_ROOT / "data" / "step07_cv_results.csv")
print(f"  Loaded {len(df_cv)} CV folds from step07_cv_results.csv")

# Prepare data for dual-metric visualization (R² and RMSE)
# Create long format for grouped bars
df_cv_long = []

for _, row in df_cv.iterrows():
    df_cv_long.append({
        'fold': f"Fold {row['fold']}",
        'metric': 'Test R²',
        'value': row['test_r2'],
        'annotation': f"{row['test_r2']:.3f}"
    })
    df_cv_long.append({
        'fold': f"Fold {row['fold']}",
        'metric': 'RMSE', 
        'value': row['rmse'],
        'annotation': f"{row['rmse']:.3f}"
    })

df_cv_plot = pd.DataFrame(df_cv_long)

# Generate faceted cross-validation plot (separate panels for R² and RMSE)
fig_cv, axes_cv = plot_comparison_bars(
    df=df_cv_plot,
    x_col='fold',
    y_col='value',
    group_col=None,
    facet_col='metric',
    annotation_col='annotation',
    xlabel='Cross-Validation Fold',
    ylabel='Value',
    title='Cross-Validation Performance',
    figsize=(12, 5),
    output_path=RQ_ROOT / "plots" / "cv_performance.png"
)

print(f"  ✓ Saved: plots/cv_performance.png")

# =============================================================================
# SUMMARY
# =============================================================================

print("\n" + "="*70)
print("PLOTTING COMPLETE")
print("="*70)
print(f"Total plots generated: 4")
print(f"  - plots/diagnostic_plots.png (regression assumptions)")
print(f"  - plots/effect_sizes.png (model effect sizes)")
print(f"  - plots/predictor_importance.png (relative importance)")
print(f"  - plots/cv_performance.png (generalizability)")
print("\nAll plots saved with 300 DPI publication quality.")
