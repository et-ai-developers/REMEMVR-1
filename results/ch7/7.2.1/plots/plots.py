# PLOT 3: MEDIATION PATH DIAGRAM
# =============================================================================

print("\nGenerating Plot 3: Mediation path diagram...")

# Load mediation plot data
df_med = pd.read_csv(RQ_ROOT / "data" / "step08_mediation_plot_data.csv")
print(f"  Loaded {len(df_med)} mediation paths from mediation_plot_data.csv")
print(f"  Columns: {list(df_med.columns)}")

# Create mediation path diagram
fig_med, ax_med = plt.subplots(figsize=(12, 8))

# Define positions for path diagram
positions = {
    'Age': (0.1, 0.5),
    'Cognitive\nTests': (0.5, 0.8),
    'REMEMVR\n(theta)': (0.9, 0.5)
}

# Draw boxes for variables
for var, (x, y) in positions.items():
    if var == 'Age':
        color = '#FF9999'  # Light red
    elif 'Cognitive' in var:
        color = '#99CCFF'  # Light blue  
    else:
        color = '#99FF99'  # Light green
    
    # Draw rounded rectangle
    bbox = dict(boxstyle="round,pad=0.3", facecolor=color, edgecolor='black', linewidth=2)
    ax_med.text(x, y, var, ha='center', va='center', fontsize=12, fontweight='bold', bbox=bbox)

# Draw paths with coefficients
paths_data = df_med.set_index('path')

# Total effect (c path) - dashed line to show it's the uncontrolled effect
total_coef = paths_data.loc['Total_Effect_c', 'coefficient']
ax_med.annotate('', xy=positions['REMEMVR\n(theta)'], xytext=positions['Age'],
               arrowprops=dict(arrowstyle='->', lw=2, color='red', linestyle='--', alpha=0.7))
ax_med.text(0.5, 0.3, f'c = {total_coef:.3f}\n(Total Effect)', ha='center', va='center', 
           fontsize=10, color='red', fontweight='bold',
           bbox=dict(boxstyle="round,pad=0.2", facecolor='white', alpha=0.8))

# Direct effect (c' path) - solid line for controlled effect
direct_coef = paths_data.loc['Direct_Effect_c_prime', 'coefficient'] 
ax_med.annotate('', xy=positions['REMEMVR\n(theta)'], xytext=positions['Age'],
               arrowprops=dict(arrowstyle='->', lw=3, color='darkred'))
ax_med.text(0.5, 0.2, f"c' = {direct_coef:.3f}\n(Direct Effect)", ha='center', va='center',
           fontsize=10, color='darkred', fontweight='bold',
           bbox=dict(boxstyle="round,pad=0.2", facecolor='white', alpha=0.8))

# Indirect path (a -> b path) through cognitive tests
# Path a: Age -> Cognitive Tests
ax_med.annotate('', xy=positions['Cognitive\nTests'], xytext=positions['Age'],
               arrowprops=dict(arrowstyle='->', lw=2, color='blue'))
ax_med.text(0.3, 0.7, 'a path\n(Age -> Cognitive)', ha='center', va='center', 
           fontsize=9, color='blue', fontweight='bold')

# Path b: Cognitive Tests -> REMEMVR  
ax_med.annotate('', xy=positions['REMEMVR\n(theta)'], xytext=positions['Cognitive\nTests'],
               arrowprops=dict(arrowstyle='->', lw=2, color='blue'))
ax_med.text(0.7, 0.7, 'b path\n(Cognitive -> VR)', ha='center', va='center',
           fontsize=9, color='blue', fontweight='bold')

# Mediation statistics
mediated_coef = paths_data.loc['Mediated_Effect_ab', 'coefficient']
proportion_mediated = mediated_coef / total_coef * 100  # Convert to percentage

# Add mediation summary box
