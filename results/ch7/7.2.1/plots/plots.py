# =============================================================================
# PLOT 4: CROSS-VALIDATION PERFORMANCE
# =============================================================================

print("\nGenerating Plot 4: Cross-validation performance...")

# Load CV plot data
df_cv = pd.read_csv(RQ_ROOT / "data" / "step08_cv_plot_data.csv")
print(f"  Loaded {len(df_cv)} CV fold results from cv_plot_data.csv")

# Prepare data for comparison bars
cv_summary = df_cv.groupby('model').agg({
    'train_r2': ['mean', 'sem'],
    'test_r2': ['mean', 'sem'],
    'rmse': ['mean', 'sem']
}).round(3)

# Flatten column names
cv_summary.columns = ['_'.join(col) for col in cv_summary.columns]
cv_summary = cv_summary.reset_index()

# Create comparison of R2 values
r2_data = []
for _, row in cv_summary.iterrows():
    # Training R2
    r2_data.append({
        'model': row['model'],
        'dataset': 'Training',
        'r2': row['train_r2_mean'],
        'r2_sem': row['train_r2_sem']
    })
    # Test R2
    r2_data.append({
        'model': row['model'], 
        'dataset': 'Test',
        'r2': row['test_r2_mean'],
        'r2_sem': row['test_r2_sem']
    })

df_r2 = pd.DataFrame(r2_data)

# Custom plotting for CV performance (since we need specific layout)
fig_cv, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))

# Panel 1: R2 comparison
models = df_r2['model'].unique()
datasets = ['Training', 'Test'] 
x_pos = np.arange(len(models))
width = 0.35

colors = {'Training': '#3498DB', 'Test': '#E74C3C'}

for i, dataset in enumerate(datasets):
    data_subset = df_r2[df_r2['dataset'] == dataset]
    r2_vals = [data_subset[data_subset['model'] == model]['r2'].iloc[0] for model in models]
    sem_vals = [data_subset[data_subset['model'] == model]['r2_sem'].iloc[0] for model in models]
    
    bars = ax1.bar(x_pos + i*width, r2_vals, width, label=dataset, 
                   color=colors[dataset], alpha=0.8, capsize=5)
    
    # Add error bars
    ax1.errorbar(x_pos + i*width, r2_vals, yerr=sem_vals, fmt='none', 
                color='black', capsize=4, alpha=0.7)
    
    # Add value labels on bars
    for j, (bar, val) in enumerate(zip(bars, r2_vals)):
        ax1.text(bar.get_x() + bar.get_width()/2, bar.get_height() + sem_vals[j] + 0.01,
                f'{val:.3f}', ha='center', va='bottom', fontweight='bold', fontsize=9)

ax1.set_xlabel('Model', fontweight='bold')
ax1.set_ylabel('R2 (Explained Variance)', fontweight='bold')
ax1.set_title('Cross-Validation Performance\n5-Fold CV Results', fontweight='bold')
ax1.set_xticks(x_pos + width/2)
ax1.set_xticklabels(['Model 1\n(Age Only)', 'Model 2\n(Age + Cognitive)'], fontsize=10)
ax1.legend()
ax1.grid(True, alpha=0.3, axis='y')
ax1.set_ylim(0, max(df_r2['r2']) * 1.3)

# Panel 2: Overfitting assessment (Train vs Test by fold)
for model in models:
    model_data = df_cv[df_cv['model'] == model]
    color = '#3498DB' if 'Age_Only' in model else '#E74C3C'
    label = 'Model 1 (Age Only)' if 'Age_Only' in model else 'Model 2 (Age + Cognitive)'
    
    ax2.scatter(model_data['train_r2'], model_data['test_r2'], 
               color=color, s=80, alpha=0.7, label=label)

# Add diagonal line (perfect generalization)
max_r2 = max(df_cv['train_r2'].max(), df_cv['test_r2'].max())
min_r2 = min(df_cv['train_r2'].min(), df_cv['test_r2'].min())
ax2.plot([min_r2, max_r2], [min_r2, max_r2], 'k--', alpha=0.5, label='Perfect Generalization')

ax2.set_xlabel('Training R2', fontweight='bold')
ax2.set_ylabel('Test R2', fontweight='bold') 
ax2.set_title('Overfitting Assessment\nTrain vs Test Performance', fontweight='bold')
ax2.legend()
ax2.grid(True, alpha=0.3)

# Add overfitting statistics
overfitting_text = "Overfitting Gap:\n"
for model in models:
    model_data = df_cv[df_cv['model'] == model]
    gap = model_data['train_r2'].mean() - model_data['test_r2'].mean()
    model_short = 'M1' if 'Age_Only' in model else 'M2'
    overfitting_text += f"{model_short}: {gap:.3f}\n"

ax2.text(0.05, 0.95, overfitting_text, transform=ax2.transAxes, 
        va='top', ha='left', fontsize=9, 
        bbox=dict(boxstyle="round,pad=0.3", facecolor='lightgray', alpha=0.8))

plt.tight_layout()

# Save CV performance plot
output_path_cv = RQ_ROOT / "plots" / "cross_validation_performance.png"
fig_cv.savefig(output_path_cv, dpi=300, bbox_inches='tight')
print(f"   Saved: plots/cross_validation_performance.png")

