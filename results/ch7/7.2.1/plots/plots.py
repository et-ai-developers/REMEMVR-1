# PLOT 1: CORRELATION HEATMAP
# =============================================================================

print("\nGenerating Plot 1: Correlation heatmap...")

# Load correlation plot data
df_corr = pd.read_csv(RQ_ROOT / "data" / "step08_correlation_plot_data.csv")
print(f"  Loaded {len(df_corr)} correlation pairs from correlation_plot_data.csv")
print(f"  Columns: {list(df_corr.columns)}")

# Create correlation matrix for heatmap
variables = ['Age', 'theta_all', 'RAVLT_T', 'BVMT_T', 'RPM_T']
corr_matrix = np.zeros((len(variables), len(variables)))
p_matrix = np.zeros((len(variables), len(variables)))

for i, var1 in enumerate(variables):
    for j, var2 in enumerate(variables):
        if i == j:
            corr_matrix[i, j] = 1.0
            p_matrix[i, j] = 0.0
        else:
            # Find correlation between var1 and var2
            subset = df_corr[(df_corr['Variable1'] == var1) & (df_corr['Variable2'] == var2)]
            if len(subset) == 0:
                subset = df_corr[(df_corr['Variable1'] == var2) & (df_corr['Variable2'] == var1)]
            
            if len(subset) > 0:
                corr_matrix[i, j] = subset.iloc[0]['correlation']
                p_matrix[i, j] = subset.iloc[0]['p_value']

# Create figure for correlation heatmap
fig_corr, ax_corr = plt.subplots(figsize=(8, 6))

# Create heatmap
mask = np.triu(np.ones_like(corr_matrix, dtype=bool))  # Mask upper triangle
im = ax_corr.imshow(corr_matrix, cmap='RdBu_r', vmin=-1, vmax=1, aspect='equal')

# Set ticks and labels
ax_corr.set_xticks(range(len(variables)))
ax_corr.set_yticks(range(len(variables)))
ax_corr.set_xticklabels(variables, rotation=45, ha='right')
ax_corr.set_yticklabels(variables)

# Add correlation values and significance stars
for i in range(len(variables)):
    for j in range(len(variables)):
        if i >= j:  # Lower triangle only
            # Correlation value
            text = ax_corr.text(j, i, f'{corr_matrix[i, j]:.3f}', 
                               ha='center', va='center', fontweight='bold')
            
            # Add significance stars
            if p_matrix[i, j] < 0.001:
                stars = '***'
            elif p_matrix[i, j] < 0.01:
                stars = '**'
            elif p_matrix[i, j] < 0.05:
                stars = '*'
            else:
                stars = ''
            
            if stars and i != j:
                ax_corr.text(j, i-0.25, stars, ha='center', va='center', 
                           fontsize=10, color='black')

# Mask upper triangle
for i in range(len(variables)):
    for j in range(len(variables)):
        if j > i:
            ax_corr.add_patch(plt.Rectangle((j-0.5, i-0.5), 1, 1, 
                                          fill=True, color='white', alpha=1))

# Add colorbar
cbar = plt.colorbar(im, ax=ax_corr, shrink=0.8)
cbar.set_label('Correlation Coefficient (r)', rotation=270, labelpad=20, fontweight='bold')

# Formatting
ax_corr.set_title('RQ 7.2.1: Correlation Matrix\nAge and Cognitive Tests vs VR Memory Performance', 
                 fontweight='bold', pad=20)
ax_corr.set_xlabel('Variables', fontweight='bold')
ax_corr.set_ylabel('Variables', fontweight='bold')

plt.tight_layout()

# Save correlation heatmap
output_path_corr = RQ_ROOT / "plots" / "correlation_heatmap.png"
fig_corr.savefig(output_path_corr, dpi=300, bbox_inches='tight')
print(f"   Saved: plots/correlation_heatmap.png")

