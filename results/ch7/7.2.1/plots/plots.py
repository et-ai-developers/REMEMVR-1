ax_med.set_aspect('equal')
ax_med.axis('off')
ax_med.set_title('RQ 7.2.1: Mediation Path Diagram\nVR Scaffolding Hypothesis (Suppression Effect)', 
                fontweight='bold', fontsize=14, pad=20)

